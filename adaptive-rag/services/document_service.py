"""
Document service: everything between "user picked a file in Streamlit" and
"it is chunked, embedded, and searchable for this chat only".

Owns the on-disk storage layout so nothing else in the app constructs
upload paths directly (section 30: never expose arbitrary filesystem paths
through the UI). Files are stored as
`{upload_dir}/{user_id}/{chat_id}/{document_id}{ext}` — the random
`document_id` (a UUID, generated by Postgres) is what's actually used on
disk, never the user-supplied filename, so path traversal / collisions are
not a concern even though the original filename is preserved for display.
"""
from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path

from config.constants import SUPPORTED_EXTENSIONS
from config.settings import get_settings
from database.models import Document
from database.repositories.chunk_repository import ChunkRepository
from database.repositories.document_repository import DocumentRepository
from ingestion.pipeline import IngestionError, ingest_document

logger = logging.getLogger(__name__)


class UploadRejectedError(ValueError):
    pass


@dataclass
class UploadOutcome:
    document: Document
    ok: bool
    chunk_count: int = 0
    error: str | None = None


class DocumentService:
    def __init__(self) -> None:
        self.documents = DocumentRepository()
        self.chunks = ChunkRepository()
        self.settings = get_settings()

    def _validate(self, filename: str, size_bytes: int) -> None:
        ext = Path(filename).suffix.lower()
        if ext not in SUPPORTED_EXTENSIONS:
            raise UploadRejectedError(
                f"Unsupported file type '{ext}'. Supported: {sorted(SUPPORTED_EXTENSIONS)}"
            )
        max_bytes = self.settings.max_upload_mb * 1024 * 1024
        if size_bytes > max_bytes:
            raise UploadRejectedError(
                f"'{filename}' is too large ({size_bytes / 1_048_576:.1f} MB). "
                f"Maximum is {self.settings.max_upload_mb} MB."
            )

    def _storage_path(self, user_id: str, chat_id: str, document_id: str, ext: str) -> Path:
        directory = self.settings.upload_dir / user_id / chat_id
        directory.mkdir(parents=True, exist_ok=True)
        return directory / f"{document_id}{ext}"

    def upload_and_ingest(
        self, *, user_id: str, chat_id: str, filename: str, file_bytes: bytes
    ) -> UploadOutcome:
        self._validate(filename, len(file_bytes))
        ext = Path(filename).suffix.lower()

        document = self.documents.create(
            user_id=user_id,
            chat_id=chat_id,
            filename=filename,
            file_type=ext.lstrip("."),
            storage_reference="pending",
        )

        target_path = self._storage_path(user_id, chat_id, document.id, ext)
        target_path.write_bytes(file_bytes)
        # storage_reference is set to the real path only after the file is
        # safely on disk, so a crash mid-write never leaves a document row
        # pointing at a file that doesn't exist.
        self.documents.set_storage_reference(document.id, str(target_path))

        try:
            chunk_count = ingest_document(
                document_id=document.id,
                user_id=user_id,
                chat_id=chat_id,
                file_path=target_path,
                filename=filename,
            )
            return UploadOutcome(document=document, ok=True, chunk_count=chunk_count)
        except IngestionError as exc:
            return UploadOutcome(document=document, ok=False, error=str(exc))

    def list_for_chat(self, chat_id: str) -> list[Document]:
        return self.documents.list_for_chat(chat_id)

    def add_more_documents(
        self, *, user_id: str, chat_id: str, uploads: list[tuple[str, bytes]]
    ) -> list[UploadOutcome]:
        """Add additional documents to an existing chat (section 36).
        Existing documents/chunks are left untouched; new chunks simply
        share the same chat_id and become searchable immediately."""
        return [
            self.upload_and_ingest(user_id=user_id, chat_id=chat_id, filename=name, file_bytes=data)
            for name, data in uploads
        ]

    def delete_document(self, *, document_id: str, user_id: str) -> bool:
        document = self.documents.get_owned(document_id, user_id)
        if document is None:
            return False
        self.chunks.delete_for_document(document_id)
        try:
            Path(document.storage_reference).unlink(missing_ok=True)
        except OSError:
            logger.warning("Could not remove file for document %s", document_id)
        return self.documents.delete(document_id, user_id)
